#!/bin/sh
# Refresh docs/trails.tsv: the Entire trails this repository cites as "trail #N",
# and no others (the project also holds private trails). Needs an Entire login;
# the build reads only the committed snapshot.
set -eu
cd "$(dirname "$0")/.."
n=$(grep -rhoE 'trails? #[0-9]+(, #[0-9]+)*' docs claims AGENTS.md | grep -oE '[0-9]+' | sort -un | paste -sd, -)
{
  printf '# Entire trails this repository cites (project et/ec1c). Generated by docs/trails-refresh.sh; do not edit.\n'
  printf '# The PDF appendix reads this snapshot, so a rebuild needs no Entire login.\n'
  printf 'number\tstatus\ttitle\n'
  entire trail list --project et/ec1c --json | jq -r --argjson n "[$n]" '.items[] | select(.number as $x | $n | index($x)) | [.number, .status, .title] | @tsv' | sort -n
} > docs/trails.tsv
