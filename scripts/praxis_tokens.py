#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Emit the Praxis design tokens the edit plane embeds, from the canonical CSS.

    uv run scripts/praxis_tokens.py emit    # write docs/notebooks/praxis-tokens.css
    uv run scripts/praxis_tokens.py check   # fail if the copy is stale
    uv run scripts/praxis_tokens.py show    # print the tokens

`design/praxis.css` in the Praxis checkout is the source of truth. This script
reads it, pulls out the custom properties, and writes a small stylesheet the
notebook loads, so the notebook's colours and scale are the Praxis ones and not
a hand-copied approximation that drifts.

The notebook is a marimo app: it cannot `<link>` a local file reliably and picks
up no site CSS, so the tokens are injected as a `<style>` block. Generating them
here rather than typing them keeps "align with our global tokens" checkable —
`--check` fails if Praxis moves and this copy does not follow.

Where Praxis is not checked out beside this repository, the script says so and
exits non-zero rather than silently emitting a stale or invented palette.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "notebooks" / "praxis-tokens.css"

# design/praxis.css relative to the Praxis checkout beside this repository
# (AGENTS.md: "Check Praxis out beside this repository").
PRAXIS_CANDIDATES = [
    ROOT.parent / "praxis" / "design" / "praxis.css",
    Path.home() / "dev" / "praxis" / "design" / "praxis.css",
]

VAR_RE = re.compile(r"(--[\w-]+)\s*:\s*([^;]+);")

# The tokens the notebook actually reads. Keeping the list explicit means a new
# Praxis token is a deliberate addition here, not an unexplained churn.
WANTED = [
    "--paper",
    "--ink",
    "--muted",
    "--rule",
    "--accent",
    "--wash",
    "--masthead",
    "--font-reading",
    "--font-label",
    "--font-data",
    "--measure",
    "--page-width",
    "--space-small",
    "--space-group",
    "--space-section",
    "--type-body",
    "--type-small",
    "--type-title",
    "--type-section",
    "--leading-reading",
    "--page-gutter",
]


def find_source() -> Path | None:
    for candidate in PRAXIS_CANDIDATES:
        if candidate.exists():
            return candidate
    return None


def parse_blocks(css: str) -> tuple[dict[str, str], dict[str, dict[str, str]], dict[str, dict[str, str]]]:
    """Return (root tokens, publisher tokens, dark tokens) as name -> value maps."""
    root: dict[str, str] = {}
    publisher: dict[str, str] = {}
    dark: dict[str, str] = {}
    dark_publisher: dict[str, str] = {}

    # :root { ... }
    m = re.search(r":root\s*\{(.*?)\}", css, re.S)
    if m:
        root = dict(VAR_RE.findall(m.group(1)))

    # [data-publisher='ethical-capital'] { ... }  (the publication authority block)
    m = re.search(
        r"\[data-publication='official'\][^{]*\[data-publisher='ethical-capital'\]\s*\{(.*?)\}",
        css,
        re.S,
    )
    if m:
        publisher = dict(VAR_RE.findall(m.group(1)))

    # dark: :root { ... } inside the prefers-color-scheme media query
    m = re.search(r"@media screen and \(prefers-color-scheme: dark\)\s*\{(.*?)\n\}", css, re.S)
    if m:
        dark_block = m.group(1)
        m2 = re.search(r":root\s*\{([^}]*)\}", dark_block)
        if m2:
            dark = dict(VAR_RE.findall(m2.group(1)))
        m3 = re.search(
            r"\[data-publication='official'\][^{]*\[data-publisher='ethical-capital'\]\s*\{([^}]*)\}",
            dark_block,
        )
        if m3:
            dark_publisher = dict(VAR_RE.findall(m3.group(1)))

    return root, {"default": publisher, "dark": dark_publisher}, {"light": root, "dark": dark}


def emit_css(css_text: str) -> str:
    root, publishers, modes = parse_blocks(css_text)
    lines: list[str] = []
    lines.append("/* Praxis design tokens for the edit plane.")
    lines.append(" *")
    lines.append(" * GENERATED by scripts/praxis_tokens.py from Praxis design/praxis.css.")
    lines.append(" * Do not edit by hand: edit Praxis, then re-run the emitter.")
    lines.append(" * A value missing from WANTED in the emitter will not appear here.")
    lines.append(" */")
    lines.append("")

    missing = [name for name in WANTED if name not in root]
    if missing:
        lines.append(f"/* Praxis no longer defines: {', '.join(missing)} */")

    lines.append(":root {")
    for name in WANTED:
        if name in root:
            lines.append(f"  {name}: {root[name].strip()};")
    lines.append("}")
    lines.append("")

    if publishers["default"]:
        lines.append("/* Ethical Capital identity, as Praxis applies it. */")
        lines.append("[data-publisher='ethical-capital'] {")
        for name in WANTED:
            if name in publishers["default"]:
                lines.append(f"  {name}: {publishers['default'][name].strip()};")
        lines.append("}")
        lines.append("")

    dark = modes["dark"]
    if dark:
        lines.append("@media screen and (prefers-color-scheme: dark) {")
        lines.append("  :root {")
        lines.append("    color-scheme: dark;")
        for name in WANTED:
            if name in dark:
                lines.append(f"    {name}: {dark[name].strip()};")
        lines.append("  }")
        if publishers["dark"]:
            lines.append("  [data-publisher='ethical-capital'] {")
            for name in WANTED:
                if name in publishers["dark"]:
                    lines.append(f"    {name}: {publishers['dark'][name].strip()};")
            lines.append("  }")
        lines.append("}")
        lines.append("")

    return "\n".join(lines)


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "emit"
    source = find_source()

    if source is None:
        print(
            "Cannot find Praxis design/praxis.css.\n"
            "Check the Praxis repository out beside this one "
            f"(looked in: {', '.join(str(p) for p in PRAXIS_CANDIDATES)}).\n"
            "The tokens are generated from that file, so there is nothing honest to emit.",
            file=sys.stderr,
        )
        return 2

    text = emit_css(source.read_text(encoding="utf-8"))
    header = f"/* source: {source} */\n"

    if cmd == "emit":
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} from {source}")
        return 0
    if cmd == "check":
        if not OUT.exists():
            print(f"{OUT.name} missing; run `uv run scripts/praxis_tokens.py emit`", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.name} is stale against {source}; run `uv run scripts/praxis_tokens.py emit`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.name} is current against Praxis")
        return 0
    if cmd == "show":
        print(text)
        return 0
    print(f"unknown command {cmd!r}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
