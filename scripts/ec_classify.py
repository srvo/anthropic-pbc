# /// script
# requires-python = ">=3.11,<3.13"
# dependencies = [
#   "torch==2.9.1",
#   "transformers==4.57.3",
#   "sentencepiece==0.2.1",
#   "protobuf==6.33.1",
#   "duckdb==2.0.0",
