#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["blake3==1.0.11"]
# ///
"""Write DATASETS.md, the central catalog of every corpus, as a Marp deck.

One registry, corpus/datasets.tsv, holds what cannot be read from files: title,
source, license, pin date, how often the source changes, and the refresh
commands. Everything else is read from the repository: each corpus's
MANIFEST.tsv (row count and BLAKE3), its committed files, and the witness runs
under proposals/<id>/. No clock: the deck changes only when the inputs change.

    uv run scripts/datasets_md.py          # write DATASETS.md
    uv run scripts/datasets_md.py check    # exit 1 if DATASETS.md is stale

Render: npx @marp-team/marp-cli DATASETS.md   (or the Marp VS Code extension)
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import blake3

sys.path.insert(0, str(Path(__file__).resolve().parent))
import attest_datasets  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "corpus" / "datasets.tsv"
OUT = ROOT / "DATASETS.md"

HEAD = """---
marp: true
paginate: true
size: 16:9
title: Datasets
style: |
  section { font-size: 22px; }
  table { font-size: 16px; }
  code { font-size: 15px; }
---

<!-- Generated by scripts/datasets_md.py from corpus/datasets.tsv and each corpus's
MANIFEST.tsv. Do not edit by hand: edit the registry and rerun. -->

# Datasets

Every corpus in this repository: where it comes from, when it was pinned, how
often the source changes, and how to rebuild it.

Model output is a witness proposal in `proposals/`, never a finding
(`docs/bert-enrichment-spec.md` §5).
"""


def b3(p: Path) -> str:
    return blake3.blake3(p.read_bytes()).hexdigest()


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def manifest_info(d: Path) -> tuple[str, str]:
    m = d / "MANIFEST.tsv"
    if not m.exists():
        return "—", "—"
    n = sum(1 for _ in m.open()) - 1
    return str(n), b3(m)[:16]


def committed_files(d: Path) -> tuple[int, int]:
    files = [p for p in d.rglob("*") if p.is_file()]
    return len(files), sum(p.stat().st_size for p in files)


def runs(ds: str) -> list[tuple[str, str, str, str]]:
    """(output dir, model, scores, backend) for every witness run under proposals/<ds>/."""
    base = ROOT / "proposals" / ds
    out = []
    for r in sorted(base.rglob("run-*.json")) if base.exists() else []:
        j = json.loads(r.read_text())
        n = j.get("n_scores") or j.get("scores") or ""
        out.append((str(r.parent.relative_to(ROOT)), r.stem[4:], str(n),
                    j.get("backend") or j.get("runtime", {}).get("backend", "")))
    return out


def epoch_table() -> list[str]:
    m = ROOT / "corpus" / "epoch" / "MANIFEST.tsv"
    rows = list(csv.DictReader(m.open(), delimiter="\t"))
    seen: dict[str, list[str]] = {}
    for r in rows:
        seen.setdefault(r["dataset"], []).append(r["updated"])
    lines = ["| Epoch dataset | Files | Source last updated |", "|---|---:|---|"]
    for k in sorted(seen):
        lines.append(f"| {k} | {len(seen[k])} | {', '.join(sorted(set(seen[k])))} |")
    return lines


def render() -> str:
    reg = list(csv.DictReader(REGISTRY.open(), delimiter="\t"))
    sig = dict(attest_datasets.status())
    o = [HEAD, "---", "", "## Overview", "",
         "| Dataset | Pinned as of | Source cadence | Manifest rows | Signature |", "|---|---|---|---:|---|"]
    for r in reg:
        d = ROOT / r["corpus_dir"] if r["corpus_dir"] != "—" else None
        n, _ = manifest_info(d) if d else ("—", "—")
        o.append(f"| [{cell(r['title'])}](#{r['id']}) | {r['pinned_as_of']} | {cell(r['source_cadence'])} | {n} | {sig.get(r['id'], '—')} |")
    for r in reg:
        d = ROOT / r["corpus_dir"] if r["corpus_dir"] != "—" else None
        n, h = manifest_info(d) if d else ("—", "—")
        nf, nb = committed_files(d) if d else (0, 0)
        o += ["", "---", "", f"<a id=\"{r['id']}\"></a>", "", f"## {r['title']}", "",
              "| | |", "|---|---|",
              f"| Source | {cell(r['source'])} |",
              f"| License | {cell(r['license'])} |",
              f"| Pinned as of | {r['pinned_as_of']} |",
              f"| Source cadence | {cell(r['source_cadence'])} |",
              f"| Committed | {cell(r['committed'])} |",
              f"| Folder | `{r['corpus_dir']}` · {nf} files · {nb / 1e6:.1f} MB |" if d else "| Folder | — |",
              f"| Manifest | {n} rows · BLAKE3 `{h}` |",
              f"| Method | [`{r['doc']}`]({r['doc']}) |",
              f"| Signature | {sig.get(r['id'], 'no corpus folder')} (`attestations/datasets/`) |",
              "", "Refresh:", "", f"    {r['refresh']}"]
        rs = runs(r["id"])
        if rs:
            o += ["", "| Witness output | Model | Scores |", "|---|---|---:|"]
            o += [f"| `{a}` | {b} | {c} |" for a, b, c, _ in rs]
        if r["id"] == "epoch":
            o += ["", "---", "", "## Epoch AI: per-dataset update dates", ""] + epoch_table()
    return "\n".join(o) + "\n"


def main() -> int:
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        ok = OUT.exists() and OUT.read_text() == text
        print("DATASETS.md is current" if ok else "DATASETS.md is stale: run uv run scripts/datasets_md.py")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
