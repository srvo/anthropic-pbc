"""Project the argument cards into a Markdown paper draft.

    uv run scripts/render_paper_from_cards.py [OUT.md]   # default argument/paper.from-cards.md

The cards are the source; this file is a projection and is never hand-edited. Each
theme becomes a section headed by its question, in sequence order. A theme with
lenses shows its default lens only; a slot with alternatives shows its default
(lowest order) card and names the others. Every sentence carries the labels it
rests on, so a reader can follow it to the quotation (claims file) or the open
source (argument/pending-sources.tsv).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_cards as cc  # noqa: E402
import hashlib

ROOT = cc.ROOT


def inputs_digest(root: Path) -> str:
    h = hashlib.sha256()
    for name in ("cards.tsv", "sequence.tsv", "themes.tsv", "pending-sources.tsv", "descartes-check.txt"):
        p = root / cc.ARG / name
        h.update(name.encode() + b"\0" + (p.read_bytes() if p.exists() else b"") + b"\0")
    return h.hexdigest()


def project(root: Path = ROOT) -> str:
    d = cc.check(cc.load(root))
    circ = cc.circles(d)
    seq = sorted(d.sequence, key=lambda r: int(r["order"]))
    slots: dict[str, list[str]] = {}
    for r in seq:
        slots.setdefault(r["slot"], []).append(r["card"])
    out = [
        "# Anthropic PBC: the argument, projected from cards",
        "",
        f"<!-- Generated by scripts/render_paper_from_cards.py from argument/*.tsv (inputs sha256:{inputs_digest(root)}). "
        "Do not edit: change the cards and re-run. -->",
        "",
        "Draft. Each sentence is one card: its statement, then `[card | circle | rests on]`. "
        "Circle 1 means every quotation under it passed Descartes; circle 0 means something under it is "
        "pending or failing.",
    ]
    for t in d.themes:
        rows = [r for r in seq if r["theme"] == t["theme"]]
        lens = t["default_lens"]
        rows = [r for r in rows if (cc.lens_of(r["card"], d.themes) or ("", lens))[1] == lens]
        out += ["", f"## {t['question']}", ""]
        if lens != "-":
            others = [x for x in t["lenses"].split(",") if x != lens]
            out += [f"*Lens: {lens}. Other lenses in the deck: {', '.join(others)}.*", ""]
        for r in rows:
            c = r["card"]
            alts = slots[r["slot"]]
            if alts[0] != c:
                continue
            note = f" Alternatives: {', '.join(alts[1:])}." if len(alts) > 1 else ""
            out.append(f"- **{r['title']}.** {d.statements[c]} "
                       f"`[{c} | {circ[c]} | {', '.join(d.cards[c])}]`{note}")
    out += ["", "---", "", f"Validator: {len(d.cards)} cards, {len(d.errors)} problems. "
            "Quotations: claims/anthropic-contrapunctus.tsv. Open sources: argument/pending-sources.tsv.", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else ROOT / cc.ARG / "paper.from-cards.md"
    out.write_text(project(), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
